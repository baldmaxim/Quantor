"""Граница рабочего пространства.

На Stage 1 здесь жил весь контроль доступа: константа и функция, возвращавшая её всем
подряд. Смысл абстракции был в том, чтобы каждый запрос уже тогда фильтровался по
`workspace_id`, и появление настоящих арендаторов поменяло источник контекста, а не все
запросы и таблицы. Так и вышло.

Теперь контекст строит `app.auth.resolver`, а модуль остался листом дерева импортов:
идентификатор dev-пространства и совместимое имя типа. Ничего, кроме них, здесь быть
не должно — иначе `app.auth.dev`, который читает отсюда константу, замкнёт импорт на себя.
"""

from __future__ import annotations

import uuid
from typing import Final

from app.auth.context import AuthContext

# Идентификатор пространства по умолчанию: одинаков между перезапусками, иначе после
# рестарта уже созданные проекты стали бы невидимыми. С миграции 0003 ему соответствует
# настоящая строка в таблице `workspaces`.
DEV_WORKSPACE_ID: Final[uuid.UUID] = uuid.UUID("00000000-0000-4000-8000-000000000001")

# Прежнее имя контекста. Обработчики читают `workspace.workspace_id` — поле сохранило имя
# и смысл, поэтому подмена источника не превратилась в правку каждого маршрута.
WorkspaceContext = AuthContext

__all__ = ["DEV_WORKSPACE_ID", "WorkspaceContext"]
